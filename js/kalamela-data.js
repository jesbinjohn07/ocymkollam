/**
 * Automatically populates the fees and rules into the DOM on load.
 */
function renderKalamelaRulesAndFees() {
  // Update fees wherever elements exist
  const dioceseEls = document.querySelectorAll('.fee-diocese-val, #feeDiocese');
  dioceseEls.forEach(el => { el.textContent = `₹${window.KALAMELA_FEES.diocese}`; });

  const centralEls = document.querySelectorAll('.fee-central-val, #feeCentral');
  centralEls.forEach(el => { el.textContent = `₹${window.KALAMELA_FEES.central}`; });

  const totalEls = document.querySelectorAll('.fee-total-val, #feeTotal');
  totalEls.forEach(el => { el.textContent = `₹${window.KALAMELA_FEES.total}`; });

  // Render 19 rules into <ol id="kalamelaRulesList"> with explicit numbers
  const rulesList = document.getElementById('kalamelaRulesList');
  if (rulesList && Array.isArray(window.KALAMELA_RULES)) {
    rulesList.innerHTML = window.KALAMELA_RULES
      .map((rule, idx) => `<li><span class="rule-num">${idx + 1}.</span><span class="rule-text">${rule}</span></li>`)
      .join('');
  }
}

// Run immediately or on DOMContentLoaded
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', renderKalamelaRulesAndFees);
} else {
  renderKalamelaRulesAndFees();
}
